const {settings,withBrowser}=require('./helpers.cjs');
const {baseURL,output}=settings();
const {default:AxeBuilder}=require('@axe-core/playwright');
const fs=require('fs');
withBrowser(async browser=>{
 const context=await browser.newContext({viewport:{width:1440,height:1100}});
 const page=await context.newPage();
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 const posted=[];page.on('request',r=>{if(!['GET','HEAD'].includes(r.method()))posted.push(r.url());});
 await page.goto(baseURL);
 await page.screenshot({path:output('desktop.png'),fullPage:true});
 await page.getByRole('button',{name:'Build my starting roadmap'}).click();
 if(!await page.locator('#concern-error').textContent())throw Error('Missing required field validation');
 await page.getByRole('button',{name:/Try a utility-bill example/}).click();
 await page.getByRole('button',{name:'Build my starting roadmap'}).click();
 await page.locator('#workspace-view').waitFor({state:'visible'});
 if(!await page.locator('#authority-list').textContent().then(x=>x.includes('utility-related')))throw Error('Keyword path missing');
 await page.locator('#authority-notes').fill('Confirm the responsible institution from published documents.');
 await page.locator('#strategy-list input').first().check();
 await page.locator('#first-step-button').click();
 await page.locator('#source-title').fill('<img src=x onerror=alert(1)> Testing source title');
 await page.locator('#source-url').fill('https://www.usa.gov/state-local-governments');
 await page.locator('#source-notes').fill('Directory only, not verification of my issue.');
 await page.getByRole('button',{name:'Add to my evidence'}).click();
 if(await page.locator('#source-list img').count())throw Error('XSS insertion');
 if(!await page.locator('#source-list').textContent().then(x=>x.includes('not independently verified')))throw Error('Missing source uncertainty');
 await page.getByRole('button',{name:/Edit source:/}).click();
 await page.locator('#source-title').fill('Government directory — user-added research lead');
 await page.getByRole('button',{name:'Save source changes'}).click();
 if(await page.locator('.source-card').count()!==1)throw Error('Editing duplicated source');
 await page.getByRole('tab',{name:'Actions & follow-through'}).click();
 await page.locator('#action-title').fill('Review the original source');
 await page.locator('#action-date').fill('2026-11-05');
 await page.getByRole('button',{name:'Add action'}).click();
 if(!await page.locator('#action-error').textContent())throw Error('Date basis not enforced');
 await page.locator('#action-basis').fill('Personal target, not an official deadline');
 await page.getByRole('button',{name:'Add action'}).click();
 if(await page.locator('.action-item').count()!==3)throw Error('Action missing');
 await page.locator('.action-item input').first().check();
 await page.getByRole('button',{name:'Create / refresh draft'}).click();
 if(!await page.locator('#draft-text').inputValue().then(x=>x.includes('Sacramento')))throw Error('Draft not personalized');
 await page.locator('#followup-notes').fill('Keep this in export.');
 const downloadPromise=page.waitForEvent('download');await page.getByRole('button',{name:'Download workspace'}).click();const download=await downloadPromise;
 const path=await download.path();const md=fs.readFileSync(path,'utf8');if(!md.includes('Keep this in export.')||!md.includes('Government directory')||!md.includes('Personal target'))throw Error('Export incomplete');
 await page.getByRole('tab',{name:'Your roadmap',exact:true}).click();
 await page.screenshot({path:output('roadmap.png'),fullPage:true});
 const desktopAxe=await new AxeBuilder({page}).analyze();
 await page.getByRole('button',{name:'Edit your story'}).click();
 await page.locator('#location').fill('Colombo, Sri Lanka');await page.locator('#country').selectOption({label:'Another country / not sure'});
 await page.getByRole('button',{name:'Build my starting roadmap'}).click();
 await page.getByRole('tab',{name:/Sources & evidence/}).click();
 if(await page.locator('#research-links a').count())throw Error('US directories shown for non-US');
 page.on('dialog',d=>d.accept());
 await page.getByRole('tab',{name:'Your roadmap',exact:true}).click();
 await page.getByRole('button',{name:'Clear this workspace',exact:true}).click();
 if(await page.locator('#concern').inputValue())throw Error('Clear failed');
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:output('mobile.png'),fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile horizontal overflow');
 const mobileAxe=await new AxeBuilder({page}).analyze();
 if(await page.evaluate(()=>localStorage.length||sessionStorage.length))throw Error('Unexpected persistence');
 if(posted.length)throw Error('User data sent to server');
 if(errors.length)throw Error('Browser errors: '+errors.join(';'));
 const reports={desktop:desktopAxe.violations.map(v=>({id:v.id,impact:v.impact,description:v.description,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary})).slice(0,12)})),mobile:mobileAxe.violations.map(v=>({id:v.id,impact:v.impact,description:v.description,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary})).slice(0,12)}))};
 fs.writeFileSync(output('accessibility.json'),JSON.stringify(reports,null,2));
 console.log(JSON.stringify({functional:'PASS',browserErrors:errors.length,dataRequests:posted.length,exportBytes:md.length,accessibility:reports},null,2));
 if(reports.desktop.length||reports.mobile.length)throw Error('Accessibility violations; see accessibility.json');
}).catch(e=>{console.error(e);process.exit(1)});
